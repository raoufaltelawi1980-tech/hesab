import { describe, expect, it } from "vitest";
import {
  buildBudgetInput,
  flowLabel,
  limitSummary,
  limitTypeLabel,
  periodTypeLabel,
  progressFill,
  progressTone,
} from "@/components/budgets/budget-labels";
import { translate } from "@/lib/messages";
import type { BudgetProgress } from "@/lib/api-client";

const CATEGORY = "cat-1";

const t = (key: Parameters<typeof translate>[1]) => translate("ar", key);
const identity = (value: number | string | null) => (value === null ? "—" : String(value));

function progress(overrides: Partial<BudgetProgress> = {}): BudgetProgress {
  return {
    budgetId: "b-1",
    period: {
      id: "p-1",
      periodType: "MONTHLY",
      periodStart: "2026-04-01",
      periodEnd: "2026-04-30",
      effectiveLimit: "500000.0000",
      carriedInAmount: "0.0000",
      amountSpent: "350000.0000",
      status: "OPEN",
      isAutoGenerated: true,
    },
    amountSpent: "350000.0000",
    limit: "500000.0000",
    remaining: "150000.0000",
    percentUsed: "70.00",
    isOverBudget: false,
    ...overrides,
  };
}

describe("budget labels", () => {
  it("labels each flow, period type and limit type", () => {
    expect(flowLabel(t, "INCOME")).toBe("وارد");
    expect(flowLabel(t, "EXPENSE")).toBe("صادر");
    expect(periodTypeLabel(t, "MONTHLY")).toBe("شهرية");
    expect(periodTypeLabel(t, "CUSTOM")).toBe("مخصصة");
    expect(limitTypeLabel(t, "FIXED_AMOUNT")).toBe("مبلغ ثابت");
    expect(limitTypeLabel(t, "PERCENTAGE")).toBe("نسبة مئوية");
  });

  it("summarises a fixed limit and a percentage limit with its basis", () => {
    expect(
      limitSummary(t, { limitType: "FIXED_AMOUNT", fixedAmount: "500000", percentValue: null, percentBasis: null }, identity),
    ).toBe("الحدّ: 500000");
    expect(
      limitSummary(t, { limitType: "PERCENTAGE", fixedAmount: null, percentValue: "30", percentBasis: "OF_TOTAL_INCOME" }, identity),
    ).toBe("النسبة المئوية: 30 — من إجمالي الوارد");
  });
});

describe("progress presentation", () => {
  it("clamps the meter width at 100 so an overspent budget cannot overflow", () => {
    expect(progressFill(progress({ percentUsed: "70.00" }))).toBe(70);
    expect(progressFill(progress({ percentUsed: "140.00", isOverBudget: true }))).toBe(100);
    expect(progressFill(progress({ percentUsed: "0.00" }))).toBe(0);
    expect(progressFill(null)).toBe(0);
  });

  it("does not throw on a non-numeric percentage", () => {
    expect(progressFill(progress({ percentUsed: "NaN" }))).toBe(0);
  });

  it("warns near the limit and turns negative past it", () => {
    expect(progressTone(progress({ percentUsed: "85.00" }))).toBe("bg-warning");
    expect(progressTone(progress({ percentUsed: "20.00" }))).toBe("bg-income");
    expect(progressTone(progress({ isOverBudget: true }))).toBe("bg-expense");
    expect(progressTone(null)).toBe("bg-line-strong");
  });
});

describe("buildBudgetInput", () => {
  it("sends only fixedAmount for a fixed limit", () => {
    expect(
      buildBudgetInput({
        name: "  مصاريف  ",
        flow: "EXPENSE",
        periodType: "MONTHLY",
        limitType: "FIXED_AMOUNT",
        amount: " 500000 ",
        percentBasis: "OF_TOTAL_EXPENSE",
        categoryId: CATEGORY,
      }),
    ).toEqual({
      name: "مصاريف",
      flow: "EXPENSE",
      periodType: "MONTHLY",
      limitType: "FIXED_AMOUNT",
      categoryId: CATEGORY,
      fixedAmount: "500000",
    });
  });

  it("sends only the percentage pair for a percentage limit", () => {
    expect(
      buildBudgetInput({
        name: "شرط",
        flow: "INCOME",
        periodType: "YEARLY",
        limitType: "PERCENTAGE",
        amount: "20",
        percentBasis: "OF_TOTAL_INCOME",
        categoryId: "",
      }),
    ).toEqual({
      name: "شرط",
      flow: "INCOME",
      periodType: "YEARLY",
      limitType: "PERCENTAGE",
      percentValue: "20",
      percentBasis: "OF_TOTAL_INCOME",
    });
  });
});
