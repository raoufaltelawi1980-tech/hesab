describe("BudgetsView alerts", () => {
  const EVENT = {
    id: "e-1",
    budgetPeriodId: PERIOD.id,
    ruleId: "r-1",
    observedAmount: "400000.0000",
    thresholdAmount: "400000.0000",
    status: "TRIGGERED",
    triggeredAt: "2026-04-05T00:00:00.000Z",
    acknowledgedAt: null,
  };

  it("shows an empty state while the budget has never crossed a threshold", async () => {
    stubRoutes();

    renderWithProviders(<BudgetsView ledgerId={LEDGER_ID} />);

    expect(await screen.findByText("التنبيهات")).toBeInTheDocument();
    expect(screen.getByText("لا توجد تنبيهات لهذه الميزانية")).toBeInTheDocument();
  });

  it("lists only the events belonging to the selected budget's periods", async () => {
    stubRoutes({
      events: [
        EVENT,
        { ...EVENT, id: "e-other", budgetPeriodId: "p-other", status: "ACKNOWLEDGED" },
      ],
    });

    renderWithProviders(<BudgetsView ledgerId={LEDGER_ID} />);

    expect(await screen.findByRole("button", { name: "تأكيد" })).toBeInTheDocument();
    expect(screen.queryByText("مؤكّد")).toBeNull();
    expect(screen.getByText(/٤٠٠٬٠٠٠/)).toBeInTheDocument();
  });

  it("acknowledges a triggered event and stops offering the action", async () => {
    const user = userEvent.setup();
    const fetchMock = stubRoutes({
      events: [EVENT],
      overrides: [
        [isAcknowledge("e-1"), { message: "تم تأكيد التنبيه", event: { id: "e-1", status: "ACKNOWLEDGED" } }],
      ],
    });

    renderWithProviders(<BudgetsView ledgerId={LEDGER_ID} />);
    await user.click(await screen.findByRole("button", { name: "تأكيد" }));

    await waitFor(() => expect(screen.queryByRole("button", { name: "تأكيد" })).toBeNull());
    expect(screen.getByText("مؤكّد")).toBeInTheDocument();
    expect(fetchMock.mock.calls.some(([url, init]) => isAcknowledge("e-1")(String(url), init))).toBe(true);
  });

  it("reports an alert that was already handled by someone else", async () => {
    const user = userEvent.setup();
    stubRoutes({
      events: [EVENT],
      overrides: [[isAcknowledge("e-1"), { message: "تم التعامل مع هذا التنبيه مسبقًا" }, 400]],
    });

    renderWithProviders(<BudgetsView ledgerId={LEDGER_ID} />);
    await user.click(await screen.findByRole("button", { name: "تأكيد" }));

    expect(await screen.findByText("تم التعامل مع هذا التنبيه مسبقًا")).toBeInTheDocument();
  });
});