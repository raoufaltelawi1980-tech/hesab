    expect(await screen.findByRole("progressbar")).toHaveAttribute("aria-valuenow", "70");

    expect(statValue("المصروف/المقبوض")).toBe(formatAmount("350000.0000", "ar"));
    expect(statValue("الحدّ")).toBe(formatAmount("500000.0000", "ar"));
    expect(statValue("المتبقي")).toBe(formatAmount("150000.0000", "ar"));
