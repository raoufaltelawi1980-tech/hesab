function stubRoutes({
  budgets = [BUDGET] as unknown[],
  progress: progressBody = PROGRESS,
  periods = [PERIOD] as unknown[],
  permissions = { isOwner: true, permissions: [] as string[] },
  events = [] as unknown[],
  overrides = [] as Route[],
} = {}) {
  return stubFetchRoutes([
    ...overrides,
    [isProgress, progressBody],
    [isPeriods, periods],
    [isAlertEvents, events],
    [isGet("/my-permissions"), permissions],
    [isGet("/accounts"), []],
    [isGet("/categories"), [EXPENSE_CATEGORY]],
    [isGet(`/ledgers/${LEDGER_ID}`), { id: LEDGER_ID, name: "متجري", type: "HOUSEHOLD", baseCurrency: null }],
    [isCreateBudget, BUDGET],
    [isArchiveBudget, { message: "تم أرشفة الميزانية", budget: BUDGET }],
    [isAddPeriod, PERIOD],
    [isBudgetList, budgets],
  ]);
}

/** Reads back the JSON body of the first call matching `match`. */
function sentBody(
  mock: ReturnType<typeof vi.fn>,
  match: (url: string, init?: RequestInit) => boolean,
): Record<string, unknown> | undefined {
  const call = mock.mock.calls.find(([url, init]) => match(String(url), init as RequestInit | undefined));
  if (!call) return undefined;
  return JSON.parse(String((call[1] as RequestInit).body)) as Record<string, unknown>;
}

/** `type="date"` inputs ignore `userEvent.type`, so the value is set directly. */
function setDate(label: string | RegExp, value: string) {
  fireEvent.change(screen.getByLabelText(label), { target: { value } });
}

/**
 * Reads a `<dd>` next to its `<dt>`, so the progress stats are asserted by label
 * instead of by formatted number, which the `ar` locale renders with Arabic-Indic
 * digits and which also repeats inside the periods table.
 */
function statValue(term: string) {
  const definition = screen.getByText(term).parentElement?.querySelector("dd");
  return definition?.textContent ?? null;
}

