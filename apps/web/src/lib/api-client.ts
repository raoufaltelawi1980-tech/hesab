/*
 * Permission vocabulary is unified on the `Permission` enum from `schema.prisma`.
 * `GET /ledgers/:id/my-permissions` returns enum members (e.g. `ENTRY_CREATE`),
 * and both `TransactionsService` and `BudgetsService` gate on the same names.
 * Owner always passes; the server remains the final gate.
 */
const PERM_ALIASES = {
  create: ["ENTRY_CREATE"],
  view: ["ENTRY_VIEW"],
  confirm: ["ENTRY_CONFIRM"],
  budgetView: ["BUDGET_VIEW"],
  budgetManage: ["BUDGET_MANAGE"],
  reportView: ["REPORT_VIEW"],
  inventoryView: ["LEDGER_VIEW"],
  inventoryManage: ["LEDGER_MANAGE"],
} as const;

export function can(
  permissions: LedgerPermissions | null,
  action: keyof typeof PERM_ALIASES,
): boolean {
  if (!permissions) return false;
  if (permissions.isOwner) return true;
  return PERM_ALIASES[action].some((p) => permissions.permissions.includes(p));
}

/**
 * No grantable permission corresponds to `ENTRY_POST`, so posting is
 * owner-only in practice. Kept explicit rather than guessed.
 */
export function canPost(permissions: LedgerPermissions | null): boolean {
  return permissions?.isOwner === true;
}

export function readToken(): string | null {
  if (typeof window === "undefined") return null;
  return window.localStorage.getItem(TOKEN_STORAGE_KEY);
}

export function writeToken(token: string | null): void {
  if (typeof window === "undefined") return;
  if (token === null) window.localStorage.removeItem(TOKEN_STORAGE_KEY);
  else window.localStorage.setItem(TOKEN_STORAGE_KEY, token);
}

export function clearSession(): void {
  writeToken(null);
  onUnauthorized(() => {});
}

/** Returns the access token; persisting it is the caller's job. */
export async function login(email: string, password: string): Promise<string> {
  const result = await apiRequest<{ accessToken: string }>("/auth/login", {
    method: "POST",
    body: { email, password },
  });
  return result.accessToken;
}

export async function logout(token: string | null): Promise<void> {
  if (!token) return;
  try {
    await apiRequest("/auth/logout", { method: "POST", body: { refreshToken: token }, token });
  } catch {
    // Revoking server-side is best effort; the local session is cleared either way.
  }
}

