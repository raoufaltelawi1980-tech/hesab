    const { svc } = service();
    const rule = await svc.addAlertRule(LEDGER_ID, BUDGET_ID, OWNER_ID, {
      name: 'تنبيه 400 ألف',
      thresholdType: 'NUMERIC',
      numericThreshold: '400000',
    });
