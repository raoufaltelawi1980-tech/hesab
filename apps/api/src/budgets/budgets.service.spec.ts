/** `this month`, so the MONTHLY fixtures line up with the service's clock. */
const TODAY = new Date();
const MONTH_START = windowForPeriodType('MONTHLY', TODAY)!.start;
const MONTH_END = windowForPeriodType('MONTHLY', TODAY)!.end;

type BudgetRowShape = Record<string, unknown>;

function makeBudget(overrides: BudgetRowShape = {}): BudgetRowShape {
  return {
    id: BUDGET_ID,
    ledgerId: LEDGER_ID,
    name: 'مصاريف التشغيل',
    flow: 'EXPENSE',
    periodType: 'MONTHLY',
    limitType: 'FIXED_AMOUNT',
    fixedAmount: new Prisma.Decimal('500000'),
    percentValue: null,
    percentBasis: null,
    currencyId: null,
    categoryId: null,
    categoryItemId: null,
    autoRenew: true,
    carryForwardEnabled: false,
    isActive: true,
    archivedAt: null,
    createdAt: new Date('2026-01-01T00:00:00Z'),
    updatedAt: new Date('2026-01-01T00:00:00Z'),
    ...overrides,
  };
}

function makePeriod(overrides: BudgetRowShape = {}): BudgetRowShape {
  return {
    id: PERIOD_ID,
    budgetId: BUDGET_ID,
    periodType: 'MONTHLY',
    periodStart: MONTH_START,
    periodEnd: MONTH_END,
    effectiveLimit: new Prisma.Decimal('500000'),
    carriedInAmount: new Prisma.Decimal('0'),
    amountSpent: new Prisma.Decimal('0'),
    status: 'OPEN',
    isAutoGenerated: true,
    closedAt: null,
    ...overrides,
  };
}

/**
 * A posted line carries the entry fields inline so the fake `journalLine`
 * finder can honour the same nested filter the real query would.
 */
type LineRow = {
  ledgerId: string;
  direction: string;
  categoryId: string | null;
  categoryItemId: string | null;
  baseAmount: Prisma.Decimal;
  entry: { status: string; kind: string; businessDate: Date };
};

function makeLine(overrides: Record<string, unknown> = {}): LineRow {
  const {
    status = 'POSTED',
    kind = 'EXPENSE',
    businessDate = new Date(MONTH_START.getTime() + 86_400_000),
    baseAmount = '100000',
    ...rest
  } = overrides;
  return {
    ledgerId: LEDGER_ID,
    direction: kind === 'INCOME' ? 'CREDIT' : 'DEBIT',
    categoryId: CATEGORY_ID as string | null,
    categoryItemId: null as string | null,
    baseAmount: new Prisma.Decimal(String(baseAmount)),
    entry: { status: String(status), kind: String(kind), businessDate: businessDate as Date },
    ...rest,
  };
}

type FakeOptions = {
  budgets?: BudgetRowShape[];
  periods?: BudgetRowShape[];
  lines?: LineRow[];
  rules?: BudgetRowShape[];
  events?: BudgetRowShape[];
  budgetsEnabled?: boolean;
  memberPermissions?: { permission: string; revokedAt: Date | null }[];
  categories?: Record<string, unknown>[];
  items?: Record<string, unknown>[];
};

function makePrisma(options: FakeOptions = {}) {
  const state = {
    budgets: [...(options.budgets ?? [makeBudget()])],
    periods: [...(options.periods ?? [makePeriod()])],
    lines: [...(options.lines ?? [])],
    rules: [...(options.rules ?? [])],
    events: [...(options.events ?? [])],
    categories: [...(options.categories ?? [])],
    items: [...(options.items ?? [])],
  };

  /** Mirrors the subset of the Prisma filter the service actually builds. */
  const matchesLine = (line: LineRow, where: Record<string, any>): boolean => {
    if (where.ledgerId && line.ledgerId !== where.ledgerId) return false;
    if (where.direction && line.direction !== where.direction) return false;
    if (where.categoryId && line.categoryId !== where.categoryId) return false;
    if (where.categoryItemId && line.categoryItemId !== where.categoryItemId) return false;
    const entry = where.entry;
    if (entry) {
      if (entry.status && line.entry.status !== entry.status) return false;
      if (entry.kind?.in && !entry.kind.in.includes(line.entry.kind)) return false;
      if (entry.businessDate?.gte && line.entry.businessDate < entry.businessDate.gte) return false;
      if (entry.businessDate?.lte && line.entry.businessDate > entry.businessDate.lte) return false;
    }
    return true;
  };

  const prisma = {
    ledger: {
      findUnique: vi.fn(async ({ where }: any) => ({
        id: LEDGER_ID,
        ownerId: OWNER_ID,
        budgetsEnabled: options.budgetsEnabled ?? true,
        baseCurrencyId: CATEGORY_ID,
        ...(where.id === OTHER_LEDGER_ID ? { id: OTHER_LEDGER_ID } : {}),
      })),
    },
    ledgerMember: {
      findUnique: vi.fn(async () => ({
        ledgerId: LEDGER_ID,
        userId: MEMBER_ID,
        permissions: options.memberPermissions ?? [],
      })),
    },
    budget: {
      findUnique: vi.fn(async ({ where }: any) =>
        state.budgets.find((row) => row.id === where.id) ?? null,
      ),
      findMany: vi.fn(async ({ where }: any) =>
        state.budgets.filter((row) => {
          if (row.ledgerId !== where.ledgerId) return false;
          // `archivedAt: null` in the filter means "hide the archived ones".
          if ('archivedAt' in where) return row.archivedAt === null;
          return true;
        }),
      ),
      create: vi.fn(async ({ data }: any) => {
        const row = makeBudget({ ...data, id: BUDGET_ID });
        state.budgets.push(row);
        return row;
      }),
      update: vi.fn(async ({ where, data }: any) => {
        const row = state.budgets.find((budget) => budget.id === where.id)!;
        Object.assign(row, data);
        return row;
      }),
    },
    budgetPeriod: {
      findMany: vi.fn(async ({ where }: any) => {
        const found = state.periods.filter((row) => row.budgetId === where.budgetId);
        const start = (row: BudgetRowShape) => (row.periodStart as unknown as Date).getTime();
        const ordered = [...found].sort((a, b) => start(a) - start(b));
        return where.orderBy?.periodStart === 'desc' ? ordered.reverse() : ordered;
      }),
      findFirst: vi.fn(async ({ where }: any) =>
        state.periods.find(
          (row) =>
            row.budgetId === where.budgetId &&
            (row.periodStart as unknown as Date).getTime() ===
              (where.periodStart as Date).getTime() &&
            (row.periodEnd as unknown as Date).getTime() === (where.periodEnd as Date).getTime(),
        ) ?? null,
      ),
      create: vi.fn(async ({ data }: any) => {
        const row = makePeriod({ ...data, id: PERIOD_ID });
        state.periods.push(row);
        return row;
      }),
    },
    journalLine: {
      findMany: vi.fn(async ({ where }: any) =>
        state.lines
          .filter((line) => matchesLine(line, where))
          .map((line) => ({ baseAmount: line.baseAmount })),
      ),
    },
    category: {
      findUnique: vi.fn(async ({ where }: any) =>
        state.categories.find((row) => row.id === where.id) ?? null,
      ),
    },
    categoryItem: {
      findUnique: vi.fn(async ({ where }: any) =>
        state.items.find((row) => row.id === where.id) ?? null,
      ),
    },
    currency: {
      findUnique: vi.fn(async ({ where }: any) =>
        where.id === CATEGORY_ID ? { id: where.id, code: 'IQD' } : null,
      ),
    },
    alertRule: {
      findMany: vi.fn(async ({ where }: any) =>
        state.rules.filter((row) => {
          if (row.budgetId !== where.budgetId) return false;
          // `enabled: true` in the filter means "only the live rules".
          if ('enabled' in where) return row.enabled === where.enabled;
          return true;
        }),
      ),
      create: vi.fn(async ({ data }: any) => {
        const row = { id: RULE_ID, enabled: true, ...data };
        state.rules.push(row);
        return row;
      }),
    },
    alertEvent: {
      findMany: vi.fn(async () => state.events),
      findFirst: vi.fn(async ({ where }: any) => {
        if (where.ruleId !== undefined && where.budgetPeriodId !== undefined) {
          return (
            state.events.find(
              (event) =>
                event.ruleId === where.ruleId && event.budgetPeriodId === where.budgetPeriodId,
            ) ?? null
          );
        }
        return state.events.find((event) => event.id === where.id) ?? null;
      }),
      findUnique: vi.fn(async ({ where }: any) =>
        state.events.find((row) => row.id === where.id) ?? null,
      ),
      create: vi.fn(async ({ data }: any) => {
        const row = { id: EVENT_ID, acknowledgedAt: null, ...data };
        state.events.push(row);
        return row;
      }),
      update: vi.fn(async ({ where, data }: any) => {
        const row = state.events.find((event) => event.id === where.id)!;
        Object.assign(row, data);
        return row;
      }),
    },
  };

  return { prisma, state };
}

function service(options: FakeOptions = {}) {
  const { prisma, state } = makePrisma(options);
  return { svc: new BudgetsService(prisma as never), prisma, state };
}

function budgetDto(overrides: Partial<CreateBudgetDto> = {}): CreateBudgetDto {
  return {
    name: 'مصاريف التشغيل',
    flow: 'EXPENSE',
    periodType: 'MONTHLY',
    limitType: 'FIXED_AMOUNT',
    fixedAmount: '500000',
    ...overrides,
  } as CreateBudgetDto;
}

describe('BudgetsService gating', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('rejects every route while budgetsEnabled is false', async () => {
    const { svc } = service({ budgetsEnabled: false });
    await expect(svc.list(LEDGER_ID, OWNER_ID)).rejects.toThrow(/FEATURE_DISABLED/);
  });

  it('answers 403 for a disabled ledger, matching the §10 contract, not a 400', async () => {
    const { svc } = service({ budgetsEnabled: false });
    const failure = svc.list(LEDGER_ID, OWNER_ID);
    await expect(failure).rejects.toBeInstanceOf(ForbiddenException);
    await expect(failure).rejects.toMatchObject({ status: 403 });
  });

  it('answers 403 when the actor holds neither the view nor the manage permission', async () => {
    const { svc } = service({ memberPermissions: [{ permission: 'VIEW_LEDGER', revokedAt: null }] });
    await expect(svc.list(LEDGER_ID, MEMBER_ID)).rejects.toBeInstanceOf(ForbiddenException);
  });

  it('checks ownership before the flag, so a stranger learns nothing about the ledger', async () => {
    const { svc } = service({ budgetsEnabled: false, memberPermissions: [] });
    const failure = svc.list(LEDGER_ID, MEMBER_ID);
    await expect(failure).rejects.toThrow('لا تملك صلاحية تنفيذ هذه العملية');
    await expect(failure).rejects.not.toThrow(/FEATURE_DISABLED/);
  });

  it('rejects a non-member with no permissions at all', async () => {
    const { svc } = service({ memberPermissions: [] });
    await expect(svc.list(LEDGER_ID, MEMBER_ID)).rejects.toThrow('لا تملك صلاحية تنفيذ هذه العملية');
  });

  it('rejects a member whose permission was revoked', async () => {
    const { svc } = service({
      memberPermissions: [{ permission: 'BUDGET_VIEW', revokedAt: new Date() }],
    });
    await expect(svc.list(LEDGER_ID, MEMBER_ID)).rejects.toThrow('لا تملك صلاحية تنفيذ هذه العملية');
  });

  it('grants BUDGET_VIEW without granting BUDGET_MANAGE', async () => {
    const { svc } = service({
      memberPermissions: [{ permission: 'BUDGET_VIEW', revokedAt: null }],
    });
    await expect(svc.list(LEDGER_ID, MEMBER_ID)).resolves.toHaveLength(1);
    await expect(svc.create(LEDGER_ID, MEMBER_ID, budgetDto())).rejects.toThrow(
      'لا تملك صلاحية تنفيذ هذه العملية',
    );
  });

  it('does not accept a permission from another family', async () => {
    const { svc } = service({
      memberPermissions: [{ permission: 'ENTRY_VIEW', revokedAt: null }],
    });
    await expect(svc.list(LEDGER_ID, MEMBER_ID)).rejects.toThrow('لا تملك صلاحية تنفيذ هذه العملية');
  });

  it('rejects a malformed ledger id before touching the database', async () => {
    const { svc, prisma } = service();
    await expect(svc.list('not-a-uuid', OWNER_ID)).rejects.toThrow('معرّف الدفتر غير صالح');
    expect(prisma.ledger.findUnique).not.toHaveBeenCalled();
  });

  it('does not leak a budget that belongs to another ledger', async () => {
    const { svc } = service({ budgets: [makeBudget({ ledgerId: OTHER_LEDGER_ID })] });
    await expect(svc.get(LEDGER_ID, BUDGET_ID, OWNER_ID)).rejects.toThrow('الميزانية غير موجودة');
  });
});

