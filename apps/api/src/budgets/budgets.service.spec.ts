describe('BudgetsService alert evaluation', () => {
  function makeRule(overrides: BudgetRowShape = {}): BudgetRowShape {
    return {
      id: RULE_ID,
      budgetId: BUDGET_ID,
      name: 'تنبيه 80%',
      thresholdType: 'PERCENTAGE',
      numericThreshold: null,
      percentThreshold: new Prisma.Decimal('80'),
      triggerOn: 'REACH',
      enabled: true,
      ...overrides,
    };
  }

  const atEightyPercent = [makeLine({ baseAmount: '400000' })];
  const createdData = (prisma: ReturnType<typeof makePrisma>['prisma']) =>
    (prisma.alertEvent.create as unknown as { mock: { calls: [{ data: any }][] } }).mock.calls[0][0].data;

  it('raises one event carrying the observed and threshold amounts', async () => {
    const { svc, prisma } = service({ rules: [makeRule()], lines: atEightyPercent });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    expect(prisma.alertEvent.create).toHaveBeenCalledTimes(1);
    const data = createdData(prisma);
    expect(data.ruleId).toBe(RULE_ID);
    expect(data.budgetPeriodId).toBe(PERIOD_ID);
    expect(data.observedAmount.toFixed(2)).toBe('80.00');
    expect(data.thresholdAmount.toFixed(4)).toBe('80.0000');
    expect(data.status).toBe('TRIGGERED');
    expect(data.acknowledgedAt).toBeUndefined();
  });

  it('measures a numeric rule against the spent amount, not the percentage', async () => {
    const { svc, prisma } = service({
      rules: [
        makeRule({
          thresholdType: 'NUMERIC',
          percentThreshold: null,
          numericThreshold: new Prisma.Decimal('400000'),
        }),
      ],
      lines: atEightyPercent,
    });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    const data = createdData(prisma);
    expect(data.observedAmount.toFixed(4)).toBe('400000.0000');
    expect(data.thresholdAmount.toFixed(4)).toBe('400000.0000');
  });

  it('stays silent while the budget is below the threshold', async () => {
    const { svc, prisma } = service({
      rules: [makeRule()],
      lines: [makeLine({ baseAmount: '300000' })],
    });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    expect(prisma.alertEvent.findFirst).not.toHaveBeenCalled();
    expect(prisma.alertEvent.create).not.toHaveBeenCalled();
  });

  it('reads EXCEED as strictly greater, so landing on the threshold is not enough', async () => {
    const { svc, prisma } = service({
      rules: [makeRule({ triggerOn: 'EXCEED' })],
      lines: atEightyPercent,
    });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(prisma.alertEvent.create).not.toHaveBeenCalled();

    const beyond = service({
      rules: [makeRule({ triggerOn: 'EXCEED' })],
      lines: [makeLine({ baseAmount: '410000' })],
    });
    await beyond.svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(beyond.prisma.alertEvent.create).toHaveBeenCalledTimes(1);
  });

  it('raises the same rule at most once per period, however often progress is read', async () => {
    const { svc, prisma, state } = service({ rules: [makeRule()], lines: atEightyPercent });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    expect(prisma.alertEvent.create).toHaveBeenCalledTimes(1);
    expect(state.events).toHaveLength(1);
  });

  it('does not re-raise an event the user already acknowledged', async () => {
    const { svc, prisma } = service({
      rules: [makeRule()],
      lines: atEightyPercent,
      events: [
        {
          id: EVENT_ID,
          ruleId: RULE_ID,
          budgetPeriodId: PERIOD_ID,
          observedAmount: new Prisma.Decimal('80'),
          thresholdAmount: new Prisma.Decimal('80'),
          status: 'ACKNOWLEDGED',
          triggeredAt: new Date('2026-04-02T00:00:00Z'),
          acknowledgedAt: new Date('2026-04-03T00:00:00Z'),
        },
      ],
    });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    expect(prisma.alertEvent.create).not.toHaveBeenCalled();
  });

  it('ignores a disabled rule', async () => {
    const { svc, prisma } = service({
      rules: [makeRule({ enabled: false })],
      lines: atEightyPercent,
    });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);

    expect(prisma.alertEvent.create).not.toHaveBeenCalled();
  });

  it('surfaces the new event in the ledger feed with its amounts as fixed-scale strings', async () => {
    const { svc } = service({ rules: [makeRule()], lines: atEightyPercent });

    await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    const events = await svc.listAlertEvents(LEDGER_ID, OWNER_ID);

    expect(events).toHaveLength(1);
    expect(events[0]).toMatchObject({
      id: EVENT_ID,
      ruleId: RULE_ID,
      budgetPeriodId: PERIOD_ID,
      observedAmount: '80.0000',
      thresholdAmount: '80.0000',
      status: 'TRIGGERED',
      acknowledgedAt: null,
    });
  });
});