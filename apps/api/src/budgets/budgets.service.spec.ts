describe('BudgetsService progress', () => {
  it('sums posted lines only and leaves remaining and percent consistent', async () => {
    const { svc } = service({
      lines: [makeLine({ baseAmount: new Prisma.Decimal('200000') }), makeLine({ baseAmount: new Prisma.Decimal('150000') })],
    });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.amountSpent).toBe('350000.0000');
    expect(progress.limit).toBe('500000.0000');
    expect(progress.remaining).toBe('150000.0000');
    expect(progress.percentUsed).toBe('70.00');
    expect(progress.isOverBudget).toBe(false);
  });

  it('excludes a confirmed-but-unposted entry from the total', async () => {
    const { svc, prisma } = service({
      lines: [
        makeLine({ baseAmount: new Prisma.Decimal('100000') }),
        makeLine({ baseAmount: new Prisma.Decimal('999999'), status: 'REVERSED' }),
      ],
    });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.amountSpent).toBe('100000.0000');
    expect(prisma.journalLine.findMany).toHaveBeenCalledWith(
      expect.objectContaining({
        where: expect.objectContaining({ entry: expect.objectContaining({ status: 'POSTED' }) }),
      }),
    );
  });

  it('excludes a posted transfer from an expense budget', async () => {
    const { svc, prisma } = service({ lines: [makeLine({ kind: 'TRANSFER' })] });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.amountSpent).toBe('0.0000');
    expect(prisma.journalLine.findMany).toHaveBeenCalledWith(
      expect.objectContaining({
        where: expect.objectContaining({ direction: 'DEBIT', entry: expect.objectContaining({ kind: { in: expect.not.arrayContaining(['TRANSFER']) } }) }),
      }),
    );
  });

  it('scopes the total to the budget category', async () => {
    const { svc, prisma } = service({
      budgets: [makeBudget({ categoryId: CATEGORY_ID })],
      lines: [makeLine({ baseAmount: new Prisma.Decimal('100000') }), makeLine({ baseAmount: new Prisma.Decimal('7000'), categoryId: null })],
    });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.amountSpent).toBe('100000.0000');
    expect(prisma.journalLine.findMany).toHaveBeenCalledWith(
      expect.objectContaining({ where: expect.objectContaining({ categoryId: CATEGORY_ID }) }),
    );
  });

  it('resolves a percentage limit from the posted income basis', async () => {
    const { svc } = service({
      budgets: [
        makeBudget({
          limitType: 'PERCENTAGE',
          fixedAmount: null,
          percentValue: new Prisma.Decimal('25'),
          percentBasis: 'OF_TOTAL_INCOME',
        }),
      ],
      periods: [makePeriod({ effectiveLimit: new Prisma.Decimal('0') })],
      lines: [
        makeLine({ kind: 'INCOME', baseAmount: new Prisma.Decimal('1000000') }),
        makeLine({ baseAmount: new Prisma.Decimal('100000') }),
      ],
    });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    // 25% of the 1,000,000 posted income is 250,000, and 100,000 is spent on it.
    expect(progress.limit).toBe('250000.0000');
    expect(progress.amountSpent).toBe('100000.0000');
    expect(progress.remaining).toBe('150000.0000');
    expect(progress.percentUsed).toBe('40.00');
  });

  it('reports a zero limit instead of dividing by zero when the basis is empty', async () => {
    const { svc } = service({
      budgets: [
        makeBudget({
          limitType: 'PERCENTAGE',
          fixedAmount: null,
          percentValue: new Prisma.Decimal('25'),
          percentBasis: 'OF_TOTAL_INCOME',
        }),
      ],
      periods: [makePeriod({ effectiveLimit: new Prisma.Decimal('0') })],
      lines: [],
    });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.limit).toBe('0.0000');
    expect(progress.percentUsed).toBe('0.00');
  });

  it('flags an overspent budget', async () => {
    const { svc } = service({ lines: [makeLine({ baseAmount: new Prisma.Decimal('800000') })] });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress.isOverBudget).toBe(true);
    expect(progress.remaining).toBe('-300000.0000');
  });

  it('returns an empty shape when the budget has no period yet', async () => {
    const { svc } = service({ periods: [] });
    const progress = await svc.progress(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(progress).toEqual({
      budgetId: BUDGET_ID,
      period: null,
      amountSpent: '0.0000',
      limit: '0.0000',
      remaining: '0.0000',
      percentUsed: '0.00',
      isOverBudget: false,
    });
  });
});

describe('BudgetsService periods', () => {
  it('returns periods with their computed spend', async () => {
    const { svc } = service({ lines: [makeLine({ baseAmount: new Prisma.Decimal('120000') })] });
    const periods = await svc.listPeriods(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(periods).toHaveLength(1);
    expect(periods[0].amountSpent).toBe('120000.0000');
  });

  it('rejects an inverted custom window', async () => {
    const { svc } = service();
    const dto: CreatePeriodDto = {
      periodStart: MONTH_END.toISOString().slice(0, 10),
      periodEnd: MONTH_START.toISOString().slice(0, 10),
    };
    await expect(svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, dto)).rejects.toThrow(
      'periodStart يجب أن يكون قبل periodEnd',
    );
  });

  it('rejects an unparsable date', async () => {
    const { svc } = service();
    await expect(
      svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, { periodStart: 'yesterday', periodEnd: 'today' }),
    ).rejects.toThrow('periodStart ليس تاريخًا صالحًا');
  });

  it('rejects a duplicate window', async () => {
    const { svc } = service();
    await expect(
      svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, {
        periodStart: MONTH_START.toISOString().slice(0, 10),
        periodEnd: MONTH_END.toISOString().slice(0, 10),
      }),
    ).rejects.toThrow('الفترة موجودة مسبقًا');
  });

  it('adds a custom period and inherits the fixed amount as its limit', async () => {
    const { svc, prisma } = service({ periods: [] });
    const period = await svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, {
      periodStart: '2026-02-01',
      periodEnd: '2026-02-28',
    });
    expect(period.periodType).toBe('CUSTOM');
    expect(period.effectiveLimit).toBe('500000.0000');
    expect(prisma.budgetPeriod.create).toHaveBeenCalledWith(
      expect.objectContaining({ data: expect.objectContaining({ isAutoGenerated: false }) }),
    );
  });

  it('accepts an explicit limit override for a percentage budget', async () => {
    const { svc } = service({
      budgets: [
        makeBudget({
          limitType: 'PERCENTAGE',
          fixedAmount: null,
          percentValue: new Prisma.Decimal('20'),
          percentBasis: 'OF_TOTAL_EXPENSE',
        }),
      ],
      periods: [],
    });
    const period = await svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, {
      periodStart: '2026-03-01',
      periodEnd: '2026-03-31',
      effectiveLimit: '75000',
    });
    expect(period.effectiveLimit).toBe('75000.0000');
  });

  it('rejects adding a period to an archived budget', async () => {
    const { svc } = service({ budgets: [makeBudget({ archivedAt: new Date('2026-02-01T00:00:00Z') })] });
    await expect(
      svc.addPeriod(LEDGER_ID, BUDGET_ID, OWNER_ID, { periodStart: '2026-02-01', periodEnd: '2026-02-28' }),
    ).rejects.toThrow(/BUDGET_ARCHIVED/);
  });
});

describe('BudgetsService update and archive', () => {
  it('renames a budget', async () => {
    const { svc } = service();
    const dto: UpdateBudgetDto = { name: 'مصاريف الحي' };
    const updated = await svc.update(LEDGER_ID, BUDGET_ID, OWNER_ID, dto);
    expect(updated.name).toBe('مصاريف الحي');
  });

  it('clears the fixed amount when switching to a percentage limit', async () => {
    const { svc } = service();
    const updated = await svc.update(LEDGER_ID, BUDGET_ID, OWNER_ID, {
      limitType: 'PERCENTAGE',
      percentValue: '35',
      percentBasis: 'OF_TOTAL_INCOME',
    });
    expect(updated.limitType).toBe('PERCENTAGE');
    expect(updated.fixedAmount).toBeNull();
    expect(updated.percentBasis).toBe('OF_TOTAL_INCOME');
  });

  it('keeps the existing limit when only the name changes', async () => {
    const { svc, prisma } = service();
    await svc.update(LEDGER_ID, BUDGET_ID, OWNER_ID, { name: 'اسم جديد' });
    expect(prisma.budget.update).toHaveBeenCalledWith({
      where: { id: BUDGET_ID },
      data: { name: 'اسم جديد' },
    });
  });

  it('rejects a partial limit update that would break exclusivity', async () => {
    const { svc } = service();
    await expect(
      svc.update(LEDGER_ID, BUDGET_ID, OWNER_ID, { percentValue: '50' }),
    ).rejects.toThrow(/BUDGET_LIMIT_EXCLUSIVE/);
  });

  it('refuses to modify an archived budget', async () => {
    const { svc } = service({ budgets: [makeBudget({ archivedAt: new Date('2026-02-01T00:00:00Z') })] });
    await expect(svc.update(LEDGER_ID, BUDGET_ID, OWNER_ID, { name: 'x' })).rejects.toThrow(/BUDGET_ARCHIVED/);
  });

  it('archives without deleting and deactivates the budget', async () => {
    const { svc, prisma } = service();
    const result = await svc.archive(LEDGER_ID, BUDGET_ID, OWNER_ID);
    expect(result.message).toBe('تم أرشفة الميزانية');
    expect(result.budget.archivedAt).not.toBeNull();
    expect(result.budget.isActive).toBe(false);
    expect(prisma.budget.update).toHaveBeenCalledWith({
      where: { id: BUDGET_ID },
      data: { archivedAt: expect.any(Date), isActive: false },
    });
    expect('delete' in prisma.budget).toBe(false);
  });

  it('refuses to archive twice', async () => {
    const { svc } = service({ budgets: [makeBudget({ archivedAt: new Date('2026-02-01T00:00:00Z') })] });
    await expect(svc.archive(LEDGER_ID, BUDGET_ID, OWNER_ID)).rejects.toThrow(/BUDGET_ARCHIVED/);
  });

  it('hides an archived budget from the list', async () => {
    const { svc } = service({
      budgets: [makeBudget(), makeBudget({ id: 'other', archivedAt: new Date('2026-02-01T00:00:00Z') })],
    });
    await expect(svc.list(LEDGER_ID, OWNER_ID)).resolves.toHaveLength(1);
  });
});

